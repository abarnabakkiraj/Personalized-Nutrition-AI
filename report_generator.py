"""
report_generator.py - PDF Report Generation Module
Creates a downloadable PDF report with blood analysis results,
nutrition recommendations, and health score summary using fpdf2.
"""

import os
from datetime import datetime
from fpdf import FPDF, XPos, YPos


class NutritionReport(FPDF):
    """Custom FPDF subclass with header and footer templates."""

    def header(self):
        self.set_font("NotoSans", "B", 14)
        self.set_fill_color(34, 139, 87)        # Green header bar
        self.set_text_color(255, 255, 255)
        self.cell(0, 14, "   Personalized Nutrition AI Report",
                  new_x=XPos.LMARGIN, new_y=YPos.NEXT, fill=True)
        self.set_text_color(0, 0, 0)
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("NotoSans", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10,
                  f"Generated by Personalized Nutrition AI  |  Page {self.page_no()}  |  {datetime.now().strftime('%d %b %Y')}",
                  align="C")


def _status_color(status: str):
    """Maps status to RGB color for visual coding."""
    return {
        "Low":    (220, 53, 69),   # Red
        "High":   (255, 140, 0),   # Orange
        "Normal": (40, 167, 69),   # Green
    }.get(status, (100, 100, 100))


def generate_pdf_report(
    user_info: dict,
    analysis_results: list,
    health_score: float,
    risk_level: str,
    output_path: str = "reports/nutrition_report.pdf"
) -> str:
    """
    Generates a styled PDF nutrition report.

    Args:
        user_info:        Dict with user details (username, full_name, age, gender).
        analysis_results: List of dicts from nutrition_engine.analyze_blood_report().
        health_score:     Float 0–100.
        risk_level:       'Low', 'Medium', or 'High'.
        output_path:      File path to save the PDF.

    Returns:
        The output path of the generated PDF.
    """
    os.makedirs("reports", exist_ok=True)
    

    pdf = NutritionReport(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)

# Add fonts BEFORE add_page()
    pdf.add_font("NotoSans", "", "fonts/NotoSans-Regular.ttf")
    pdf.add_font("NotoSans", "B", "fonts/NotoSans-Bold.ttf")
    pdf.add_font("NotoSans", "I", "fonts/NotoSans-Regular.ttf")

    pdf.add_page()

    # ── Section 1: Patient Info ───────────────────────────────────────────────
    pdf.set_font("NotoSans", "B", 12)
    pdf.set_fill_color(240, 240, 240)
    pdf.cell(0, 8, "Patient Information", new_x=XPos.LMARGIN, new_y=YPos.NEXT, fill=True)
    pdf.ln(2)

    pdf.set_font("NotoSans", "", 10)
    info_lines = [
        ("Name",            user_info.get("full_name", user_info.get("username", "N/A"))),
        ("Age",             str(user_info.get("age", "N/A"))),
        ("Gender",          user_info.get("gender", "N/A")),
        ("Report Date",     datetime.now().strftime("%d %B %Y, %H:%M")),
    ]
    for label, value in info_lines:
        pdf.set_font("NotoSans", "B", 10)
        pdf.cell(40, 7, f"{label}:")
        pdf.set_font("NotoSans", "", 10)
        pdf.cell(0, 7, value, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.ln(4)

    # ── Section 2: Health Score Summary ──────────────────────────────────────
    pdf.set_font("NotoSans", "B", 12)
    pdf.set_fill_color(240, 240, 240)
    pdf.cell(0, 8, "Health Summary", new_x=XPos.LMARGIN, new_y=YPos.NEXT, fill=True)
    pdf.ln(3)

    risk_colors = {"Low": (40, 167, 69), "Medium": (255, 140, 0), "High": (220, 53, 69)}
    r, g, b = risk_colors.get(risk_level, (100, 100, 100))

    pdf.set_font("NotoSans", "B", 11)
    pdf.cell(60, 8, f"Overall Health Score:")
    pdf.set_font("NotoSans", "B", 14)
    pdf.set_text_color(r, g, b)
    pdf.cell(0, 8, f"{health_score}/100  [{risk_level} Risk]",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_text_color(0, 0, 0)
    pdf.ln(4)

    # ── Section 3: Blood Parameter Table ─────────────────────────────────────
    pdf.set_font("NotoSans", "B", 12)
    pdf.set_fill_color(240, 240, 240)
    pdf.cell(0, 8, "Blood Parameter Analysis", new_x=XPos.LMARGIN, new_y=YPos.NEXT, fill=True)
    pdf.ln(3)

    # Table header
    pdf.set_font("NotoSans", "B", 9)
    pdf.set_fill_color(34, 139, 87)
    pdf.set_text_color(255, 255, 255)
    col_widths = [55, 30, 50, 25]
    headers    = ["Parameter", "Your Value", "Normal Range", "Status"]
    for header, w in zip(headers, col_widths):
        pdf.cell(w, 8, header, border=1, fill=True)
    pdf.ln()
    pdf.set_text_color(0, 0, 0)

    # Table rows
    pdf.set_font("NotoSans", "", 9)
    for i, row in enumerate(analysis_results):
        fill_color = (248, 248, 248) if i % 2 == 0 else (255, 255, 255)
        pdf.set_fill_color(*fill_color)

        r, g, b = _status_color(row["status"])

        pdf.cell(col_widths[0], 7, row["label"], border=1, fill=True)
        pdf.cell(col_widths[1], 7, f"{row['value']} {row['unit']}", border=1, fill=True)
        pdf.cell(col_widths[2], 7, row["normal_range"], border=1, fill=True)

        pdf.set_text_color(r, g, b)
        pdf.set_font("NotoSans", "B", 9)
        pdf.cell(col_widths[3], 7, row["status"], border=1, fill=True)
        pdf.set_text_color(0, 0, 0)
        pdf.set_font("NotoSans", "", 9)
        pdf.ln()

    pdf.ln(6)

    # ── Section 4: Detailed Recommendations ──────────────────────────────────
    pdf.set_font("NotoSans", "B", 12)
    pdf.set_fill_color(240, 240, 240)
    pdf.cell(0, 8, "Personalized Nutrition Recommendations", new_x=XPos.LMARGIN, new_y=YPos.NEXT, fill=True)
    pdf.ln(3)

    abnormal = [r for r in analysis_results if r["status"] != "Normal"]

    if not abnormal:
        pdf.set_font("NotoSans", "", 10)
        pdf.set_text_color(40, 167, 69)
        pdf.multi_cell(0, 7, "All parameters are within normal range. Maintain a balanced diet and healthy lifestyle!")
        pdf.set_text_color(0, 0, 0)
    else:
        for rec in abnormal:
            r, g, b = _status_color(rec["status"])

            # Parameter heading
            pdf.set_font("NotoSans", "B", 11)
            pdf.set_text_color(r, g, b)
            pdf.cell(0, 8, f"  {rec['label']} — {rec['status']}  ({rec['value']} {rec['unit']})",
                     new_x=XPos.LMARGIN, new_y=YPos.NEXT)
            pdf.set_text_color(0, 0, 0)

            # Recommended foods
            if rec.get("foods"):
                pdf.set_font("NotoSans", "B", 9)
                pdf.cell(0, 6, "  Recommended Foods:", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
                pdf.set_font("NotoSans", "", 9)
                for food in rec["foods"]:
                    # Strip emoji for PDF compatibility
                    food_clean = food.encode("ascii", "ignore").decode().strip()
                    if food_clean:
                        pdf.cell(8, 5, "")
                        pdf.cell(0, 5, f"• {food_clean}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            # Foods to avoid
            if rec.get("avoid"):
                pdf.set_font("NotoSans", "B", 9)
                pdf.cell(0, 6, "  Foods to Avoid:", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
                pdf.set_font("NotoSans", "", 9)
                for food in rec["avoid"]:
                    pdf.cell(8, 5, "")
                    pdf.cell(0, 5, f"• {food}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            # Tips
            if rec.get("tips"):
                pdf.set_font("NotoSans", "B", 9)
                pdf.cell(0, 6, "  Health Tips:", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
                pdf.set_font("NotoSans", "I", 9)
                for tip in rec["tips"]:
                    pdf.cell(8, 5, "")
                    pdf.multi_cell(0, 5, f"• {tip}")

            pdf.ln(3)

    # ── Section 5: Disclaimer ─────────────────────────────────────────────────
    pdf.ln(4)
    pdf.set_font("NotoSans", "I", 8)
    pdf.set_text_color(120, 120, 120)
    pdf.multi_cell(0, 5,
        "DISCLAIMER: This report is generated by an AI system for informational purposes only. "
        "It does not constitute medical advice. Always consult a qualified healthcare professional "
        "before making any changes to your diet or treatment plan.")

    pdf.output(output_path)
    return output_path
